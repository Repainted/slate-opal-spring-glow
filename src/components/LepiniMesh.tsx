export function LepiniMesh({
  progress,
  className = "h-full w-full",
}: {
  progress: number;
  className?: string;
}) {
  const uid = useId();
  const n = MESH_EDGES.length;
  return (
    <svg viewBox="0 0 480 168" className={className} fill="none" aria-hidden>
      <g stroke="#B57C50" strokeWidth="2.15" strokeLinecap="round" strokeLinejoin="round">
        {MESH_EDGES.map(([x1, y1, x2, y2], i) => {
          const start = (i / n) * 0.5;
          const local = Math.max(0, Math.min(1, (progress - start) / 0.42));
          const len = Math.hypot(x2 - x1, y2 - y1);
          return (
            <line
              key={`${uid}-${i}`}
              x1={x1}
              y1={y1}
              x2={x2}
              y2={y2}
              strokeDasharray={len}
              strokeDashoffset={len * (1 - local)}
            />
          );
        })}
      </g>
    </svg>
  );
}